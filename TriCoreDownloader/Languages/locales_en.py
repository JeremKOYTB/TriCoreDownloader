import base64
import sys
from ..config import APP_VERSION

try:
    from ..logos import TCD_MAIN_LOGO, TCD_MAIN_LOGO_APPLE
except ImportError:
    try:
        from .logos import TCD_MAIN_LOGO, TCD_MAIN_LOGO_APPLE
    except ImportError:
        TCD_MAIN_LOGO = b""
        TCD_MAIN_LOGO_APPLE = b""

if sys.platform == "darwin" and TCD_MAIN_LOGO_APPLE:
    _raw_logo = TCD_MAIN_LOGO_APPLE
else:
    _raw_logo = TCD_MAIN_LOGO

try:
    from PyQt6.QtGui import QImage, QPainter
    from PyQt6.QtCore import QByteArray, QBuffer, QIODevice, Qt, QRectF
    from PyQt6.QtSvg import QSvgRenderer

    _img = QImage(512, 512, QImage.Format.Format_ARGB32_Premultiplied)
    _img.fill(Qt.GlobalColor.transparent)

    _renderer = QSvgRenderer(QByteArray(_raw_logo))
    if _renderer.isValid():
        _painter = QPainter(_img)
        _painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        _painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
        _renderer.render(_painter, QRectF(0, 0, 512, 512))
        _painter.end()

        _buf = QBuffer()
        _buf.open(QIODevice.OpenModeFlag.WriteOnly)
        _img.save(_buf, "PNG")
        _LOGO_B64 = base64.b64encode(bytes(_buf.data())).decode("utf-8")
        _LOGO_MIME = "image/png"
    else:
        raise ValueError("SVG render failed")
except Exception:
    _LOGO_B64 = base64.b64encode(_raw_logo).decode("utf-8")
    _LOGO_MIME = "image/svg+xml"

